import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { parseText, type ParsedItem } from "../src/callables/parseItems.js";
import { AnthropicTransport } from "../src/llm/anthropic.js";
import { ClassifyingLlm } from "../src/llm/provider.js";
import { RecordingTransport, ReplayTransport } from "../src/llm/transport.js";
import { Catalog } from "../src/lib/catalog.js";

/**
 * Golden test (prompt B4) over fixtures/parse_cases.json, scored by the fixture's own rules.
 * Default: replays test/recordings/ (offline; a case whose LLM call has no recording uses the
 * fallback path). `RECORD=1 ANTHROPIC_API_KEY=… npm run test:unit -- golden` records once.
 * The ≥ 90% gate applies once recordings exist; the report is written either way.
 */
interface Expected {
  canonicalId: string;
  qty?: number;
  unit?: string;
}
interface Case {
  id: string;
  tags: string[];
  text: string;
  localeHints: string[];
  expect: Expected[];
}

const root = resolve(import.meta.dirname, "..");
const recordings = resolve(root, "test/recordings");
const cases = (
  JSON.parse(readFileSync(resolve(root, "../../fixtures/parse_cases.json"), "utf8")) as { cases: Case[] }
).cases;

export function score(parsed: ParsedItem[], expected: Expected[]): string | null {
  const left = [...expected];
  for (const item of parsed) {
    const i = left.findIndex((e) => e.canonicalId === item.canonicalId);
    if (i < 0) return `unexpected item "${item.name}" (${item.canonicalId ?? "no id"})`;
    const e = left[i];
    if (e?.qty !== undefined && Math.abs((item.qty ?? Number.NaN) - e.qty) > 0.001)
      return `${e.canonicalId}: qty ${String(item.qty)} ≠ ${String(e.qty)}`;
    if (e?.unit !== undefined && item.unit !== e.unit)
      return `${e.canonicalId}: unit ${String(item.unit)} ≠ ${e.unit}`;
    left.splice(i, 1);
  }
  return left.length > 0 ? `missing ${left.map((e) => e.canonicalId).join(", ")}` : null;
}

function transport() {
  if (process.env.RECORD === "1") {
    const key = process.env.ANTHROPIC_API_KEY;
    if (!key) throw new Error("RECORD=1 needs ANTHROPIC_API_KEY");
    return new RecordingTransport(new AnthropicTransport(key), recordings);
  }
  return new ReplayTransport(recordings);
}

describe("golden: fixtures/parse_cases.json through parseItems", () => {
  it("scores every case and writes test/golden-report.md", { timeout: 300_000 }, async () => {
    const llm = new ClassifyingLlm(
      transport(),
      process.env.LLM_MODEL_FAST ?? "claude-haiku-5-5",
      Catalog.bundled.items.map((i) => i.id),
    );
    const rows: { id: string; ok: boolean; source: string; reason: string }[] = [];
    for (const c of cases) {
      const result = await parseText(c.text, {
        localeHints: c.localeHints,
        aliases: new Map(),
        targetLanguages: ["ar", "tr", "en"],
        llm,
      });
      const failure = score(result.items, c.expect);
      rows.push({ id: c.id, ok: failure === null, source: result.source, reason: failure ?? "" });
    }
    const passed = rows.filter((r) => r.ok).length;
    const recorded = existsSync(recordings)
      ? readdirSync(recordings).filter((f) => f.endsWith(".json")).length
      : 0;
    const rate = passed / rows.length;
    const report = [
      "# Golden report: fixtures/parse_cases.json",
      "",
      `Generated by \`test/golden.test.ts\`. Passed **${String(passed)} / ${String(rows.length)}** (${(rate * 100).toFixed(0)}%).`,
      `LLM recordings: ${String(recorded)}${recorded === 0 ? " (none yet: cases needing the LLM ran on the fallback path; record with RECORD=1 once an API key exists)" : ""}.`,
      "",
      "| Case | Result | Source | Reason |",
      "| --- | --- | --- | --- |",
      ...rows.map((r) => `| ${r.id} | ${r.ok ? "pass" : "FAIL"} | ${r.source} | ${r.reason} |`),
      "",
    ].join("\n");
    writeFileSync(resolve(root, "test/golden-report.md"), report);

    if (recorded > 0) expect(rate).toBeGreaterThanOrEqual(0.9);
    else expect(passed).toBeGreaterThan(0);
  });
});
